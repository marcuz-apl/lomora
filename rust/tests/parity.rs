//! Live parity sweep. Not part of `cargo test`: it needs both servers and the mock running,
//! so it is `#[ignore]`d.
//!
//! ```
//! cd rust && cargo run --bin mock_upstream 8600          # mock upstream
//! cd rust && PORT=8502 LOMORA_DB=/tmp/parity-rs.db cargo run
//! python main.py                                          # reference app on :8501
//! cd rust && cargo test --test parity -- --ignored --nocapture
//! ```
//!
//! Both servers must start with empty history. The test drives identical scripted requests and
//! compares parsed `serde_json::Value`s — float text (`23.5` vs `23.50`) must not create false
//! failures — plus the ordered key/type shape, which is the part `index.html` actually depends
//! on. Deterministic fields are compared for equality; live measurements (CPU, latency) are
//! compared for type and shape only. The report is written to `docs/parity-report.md`.

use serde_json::Value;

fn py(p: &str) -> String { format!("http://127.0.0.1:8501{p}") }
fn rs(p: &str) -> String { format!("http://127.0.0.1:8502{p}") }

fn mock_base() -> String {
    std::env::var("MOCK_BASE").unwrap_or_else(|_| "http://127.0.0.1:8600".into())
}

/// Ordered `path=type` for every key, descending into arrays through their first element.
/// `type` separates the cases the dashboard branches on: `null`, bool, integer, float, string,
/// array, object. Python's `True` and `1` are different JSON values, so serde's split is right.
fn shape(v: &Value) -> Vec<String> {
    fn walk(v: &Value, path: &str, acc: &mut Vec<String>) {
        let ty = match v {
            Value::Null => "null",
            Value::Bool(_) => "bool",
            Value::Number(n) => if n.is_i64() || n.is_u64() { "int" } else { "float" },
            Value::String(_) => "string",
            Value::Array(_) => "array",
            Value::Object(_) => "object",
        };
        acc.push(format!("{path}={ty}"));
        match v {
            Value::Object(m) => { for (k, child) in m { walk(child, &format!("{path}.{k}"), acc); } }
            Value::Array(a) => { if let Some(first) = a.first() { walk(first, &format!("{path}[]"), acc); } }
            _ => {}
        }
    }
    let mut acc = Vec::new();
    walk(v, "", &mut acc);
    acc
}

fn keys(v: &Value) -> Vec<String> {
    v.as_object().map(|o| o.keys().cloned().collect()).unwrap_or_default()
}

/// Replace pydantic's `ctx.error` sentence (CPython `json` wording) with a placeholder so the
/// structural parts of a `json_invalid` entry can still be compared exactly. Only applied to
/// malformed-body cases; every other 422 is compared verbatim.
fn strip_json_error_text(v: &Value) -> Value {
    let mut v = v.clone();
    if let Some(detail) = v.get_mut("detail").and_then(Value::as_array_mut) {
        for entry in detail {
            if let Some(ctx) = entry.get_mut("ctx").and_then(Value::as_object_mut)
                && ctx.contains_key("error")
            {
                ctx.insert("error".into(), Value::String("<json wording>".into()));
            }
        }
    }
    v
}

async fn pair_get(c: &reqwest::Client, path: &str) -> (reqwest::Response, reqwest::Response) {
    (c.get(py(path)).send().await.unwrap(), c.get(rs(path)).send().await.unwrap())
}

async fn pair_post(c: &reqwest::Client, path: &str, body: &Value)
    -> (reqwest::Response, reqwest::Response)
{
    (c.post(py(path)).json(body).send().await.unwrap(),
     c.post(rs(path)).json(body).send().await.unwrap())
}

#[tokio::test]
#[ignore = "needs Python :8501, Rust :8502 and the mock on :8600"]
async fn every_endpoint_matches_on_keys_types_order_and_deterministic_values() {
    let c = reqwest::Client::new();
    let mock = mock_base();
    let mut report = String::from(
        "# Parity report\n\n\
         Part 1 is regenerated by `cargo test --test parity -- --ignored`; parts 2-4 are the \
         manual Task 8 evidence and are not touched by the test (re-append them if it is rerun).\n\n");
    let mut diffs = Vec::new();

    // ── 1. GET endpoints ────────────────────────────────────────────────────────────────
    for (path, expect) in [("/api/hardware", "shape"), ("/api/models", "exact"),
                           ("/api/profile", "shape"), ("/api/history", "shape")] {
        let p = if path == "/api/models" { format!("{path}?base_url={mock}") } else { path.into() };
        let (a, b) = pair_get(&c, &p).await;
        if a.status() != b.status() { diffs.push(format!("{p}: status {} vs {}", a.status(), b.status())); }
        let va: Value = a.json().await.unwrap();
        let vb: Value = b.json().await.unwrap();
        if expect == "exact" {
            if va != vb { diffs.push(format!("{p}: body differs\n  py={va}\n  rs={vb}")); }
        } else if shape(&va) != shape(&vb) {
            diffs.push(format!("{p}: shape differs\n  py={:?}\n  rs={:?}", shape(&va), shape(&vb)));
        }
        report.push_str(&format!("- `GET {p}` {} — shape `{:?}`\n",
                                 if shape(&va) == shape(&vb) { "MATCH" } else { "DIFFER" }, shape(&va)));
    }

    // ── 2. Profile values the machine fixes ────────────────────────────────────────────
    let (pa, pb): (Value, Value) = {
        let (a, b) = pair_get(&c, "/api/profile").await;
        (a.json().await.unwrap(), b.json().await.unwrap())
    };
    for field in ["name", "notes", "cpu_cores_logical", "cpu_cores_physical", "ram_total_gb",
                  "gpu", "gpu_vram_gb", "gpu_driver"] {
        if pa.get(field) != pb.get(field) {
            diffs.push(format!("/api/profile.{field}: py={} rs={}",
                               pa.get(field).map(Value::to_string).unwrap_or("absent".into()),
                               pb.get(field).map(Value::to_string).unwrap_or("absent".into())));
        }
    }
    for field in ["cpu", "os"] {
        let (a, b) = (pa[field].as_str(), pb[field].as_str());
        if !(a.is_some() && b.is_some()) {
            diffs.push(format!("/api/profile.{field}: one side is not a string: py={a:?} rs={b:?}"));
        }
    }

    // ── 3. The single-run endpoint ──────────────────────────────────────────────────────
    let single = serde_json::json!({"model": "mock-a", "base_url": mock, "max_tokens": 20});
    let (a, b) = pair_post(&c, "/api/test", &single).await;
    if a.status() != b.status() { diffs.push(format!("/api/test: status {} vs {}", a.status(), b.status())); }
    let (ra, rb): (Value, Value) = (a.json().await.unwrap(), b.json().await.unwrap());
    if shape(&ra) != shape(&rb) {
        diffs.push(format!("/api/test: shape differs\n  py={:?}\n  rs={:?}", shape(&ra), shape(&rb)));
    }
    for field in ["model", "max_tokens", "tokens"] {
        if ra[field] != rb[field] { diffs.push(format!("/api/test.{field}: py={} rs={}", ra[field], rb[field])); }
    }
    if ra["ttft_ms"].is_null() != rb["ttft_ms"].is_null() {
        diffs.push(format!("/api/test.ttft_ms nullness differs: py={} rs={}", ra["ttft_ms"], rb["ttft_ms"]));
    }
    for field in ["ttft_ms", "total_s", "tok_per_s"] {
        if !rb[field].is_null() && !rb[field].is_number() {
            diffs.push(format!("/api/test.{field}: rust is not numeric: {}", rb[field]));
        }
    }
    report.push_str(&format!("- `POST /api/test` deterministic fields MATCH (model, max_tokens, tokens={})\n",
                             rb["tokens"]));

    // ── 4. The stress endpoint ──────────────────────────────────────────────────────────
    let stress = serde_json::json!({"model": "mock-a", "base_url": mock, "max_tokens": 8,
                                    "concurrency": 2, "requests": 4});
    let (a, b) = pair_post(&c, "/api/stress", &stress).await;
    let (sa, sb): (Value, Value) = (a.json().await.unwrap(), b.json().await.unwrap());
    if shape(&sa) != shape(&sb) {
        diffs.push(format!("/api/stress: shape differs\n  py={:?}\n  rs={:?}", shape(&sa), shape(&sb)));
    }
    for field in ["model", "base_url", "concurrency", "requests", "success", "errors",
                  "total_tokens", "error_samples"] {
        if sa[field] != sb[field] {
            diffs.push(format!("/api/stress.{field}: py={} rs={}", sa[field], sb[field]));
        }
    }
    report.push_str(&format!("- `POST /api/stress` deterministic fields MATCH (success={}, errors={}, total_tokens={})\n",
                             sb["success"], sb["errors"], sb["total_tokens"]));

    // ── 5. History after identical scripted runs ────────────────────────────────────────
    let (a, b) = pair_get(&c, "/api/history").await;
    let (ha, hb): (Value, Value) = (a.json().await.unwrap(), b.json().await.unwrap());
    let (arr_a, arr_b) = (ha.as_array().unwrap(), hb.as_array().unwrap());
    if arr_a.len() != arr_b.len() {
        diffs.push(format!("/api/history: {} rows vs {}", arr_a.len(), arr_b.len()));
    }
    let models_a: Vec<&str> = arr_a.iter().filter_map(|r| r["model"].as_str()).collect();
    let models_b: Vec<&str> = arr_b.iter().filter_map(|r| r["model"].as_str()).collect();
    if models_a != models_b {
        diffs.push(format!("/api/history order: py={models_a:?} rs={models_b:?}"));
    }
    if let (Some(fa), Some(fb)) = (arr_a.first(), arr_b.first()) {
        if keys(fa) != keys(fb) { diffs.push(format!("/api/history keys: py={:?} rs={:?}", keys(fa), keys(fb))); }
        if fa["ttft_ms"].is_null() != fb["ttft_ms"].is_null() {
            diffs.push(format!("/api/history[0].ttft_ms nullness: py={} rs={}", fa["ttft_ms"], fb["ttft_ms"]));
        }
    }
    report.push_str(&format!("- `GET /api/history` {} rows in the same order: `{models_b:?}`\n", arr_b.len()));

    // ── 6. Validation bodies, compared exactly ──────────────────────────────────────────
    let bodies = [
        ("/api/test", serde_json::json!({"model": 5, "max_tokens": 5000})),
        ("/api/test", serde_json::json!({"max_tokens": "5000"})),
        ("/api/test", serde_json::json!({"max_tokens": 2049.0})),
        ("/api/test", serde_json::json!({"max_tokens": 0})),
        ("/api/stress", serde_json::json!({"model": "m", "concurrency": 33})),
        ("/api/stress", serde_json::json!({"model": "m", "requests": 501})),
    ];
    for (path, body) in bodies {
        let (a, b) = pair_post(&c, path, &body).await;
        let (va, vb): (Value, Value) = (a.json().await.unwrap(), b.json().await.unwrap());
        if va != vb {
            diffs.push(format!("422 {path} {body}:\n  py={va}\n  rs={vb}"));
        }
        if keys(&va["detail"][0]) != keys(&vb["detail"][0]) {
            diffs.push(format!("422 {path} {body} detail keys differ"));
        }
        report.push_str(&format!("- `POST {path}` {body} → 422 detail MATCH\n"));
    }
    // Malformed JSON needs a raw body, not `.json()`. Pydantic's `ctx.error` is CPython `json`'s
    // sentence; serde_json words the same syntax error differently ("key must be a string at
    // line 1 column 3" versus "Expecting property name enclosed in double quotes"). The offset
    // in `loc`, the type, the msg and the input are the contract and are compared exactly; the
    // free-text sentence is a documented deviation (extension of spec deviation 1).
    for raw in ["{ not json", "{\"a\": 1,}"] {
        let (a, b) = (
            c.post(py("/api/test")).header("content-type", "application/json").body(raw).send().await.unwrap(),
            c.post(rs("/api/test")).header("content-type", "application/json").body(raw).send().await.unwrap(),
        );
        let (va, vb): (Value, Value) = (a.json().await.unwrap(), b.json().await.unwrap());
        let (ea, eb) = (&va["detail"][0]["ctx"]["error"], &vb["detail"][0]["ctx"]["error"]);
        if !(ea.is_string() && eb.is_string()) {
            diffs.push(format!("422 malformed {raw:?}: ctx.error missing: py={ea} rs={eb}"));
        }
        if strip_json_error_text(&va) != strip_json_error_text(&vb) {
            diffs.push(format!("422 malformed {raw:?}:\n  py={va}\n  rs={vb}"));
        }
    }
    report.push_str("- malformed bodies → 422 `json_invalid` MATCH on type/loc/msg/input \
                     (`ctx.error` prose differs: CPython json vs serde_json)\n");

    // ── 7. Profile write, then content types ────────────────────────────────────────────
    let (a, b) = pair_post(&c, "/api/profile", &serde_json::json!({"name": "Parity rig"})).await;
    let (wa, wb): (Value, Value) = (a.json().await.unwrap(), b.json().await.unwrap());
    if wa != wb { diffs.push(format!("POST /api/profile:\n  py={wa}\n  rs={wb}")); }

    for path in ["/", "/index.html", "/api/profile"] {
        let (a, b) = pair_get(&c, path).await;
        let (ca, cb) = (a.headers()["content-type"].to_str().unwrap().to_string(),
                        b.headers()["content-type"].to_str().unwrap().to_string());
        if ca.split(';').next() != cb.split(';').next() {
            diffs.push(format!("{path} content-type: py={ca} rs={cb}"));
        }
        report.push_str(&format!("- `GET {path}` content-type: py=`{ca}` rs=`{cb}`\n"));
    }

    report.push_str("\n## Deviations expected and tested around\n\n");
    report.push_str("- `profile.cpu` / `profile.os` wording (spec deviations 2 and 3)\n");
    report.push_str("- error-detail prose (spec deviation 1)\n");
    report.push_str("- live counters and latencies: compared by type, not value\n");
    report.push_str("\n## Result\n\n");
    if diffs.is_empty() {
        report.push_str("Every endpoint MATCHES on keys, types, order and deterministic values.\n");
    } else {
        report.push_str("DIFFERENCES (each an unexpected task defect unless listed above):\n\n");
        for d in &diffs { report.push_str(&format!("- {d}\n")); }
    }
    report.push('\n');
    std::fs::write("../docs/parity-report.md", &report).expect("write docs/parity-report.md");
    println!("{report}");
    assert!(diffs.is_empty(), "parity differences:\n{}", diffs.join("\n"));
}
